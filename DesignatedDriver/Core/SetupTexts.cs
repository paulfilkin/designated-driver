namespace DesignatedDriver.Core;

/// <summary>
/// The issue, commit message and pull request body the set-up writes when a repository with history gets its
/// convention files, and the ones an update from the Check screen writes: the convention's own rule, applied
/// to itself. Repository content, so English and not in the resources.
/// </summary>
public static class SetupTexts
{
    public static string CommitMessage(int issue)
        => ConventionContent.SetupIssueTitle + "\n\nWritten by Repo Starter: the contributing guide, the Git guide, the\n"
         + "pull request and issue templates, CODEOWNERS, the CI, guard and board\n"
         + "workflows, the Dependabot configuration, the local hooks and the\nconvention manifest."
         + (issue > 0 ? $"\n\nCloses #{issue}\n" : "\n");

    public static string IssueBody(SetupAnswers a)
        => "Repo Starter is setting this repository up to convention v1: labels, a project board, the merge settings, "
         + "Dependabot, local hooks, and the convention files in a pull request.\n\n"
         + $"- Language: {ProjectLanguage.DisplayName(a.Language)}\n"
         + $"- Required check: {a.RequiredCheck}\n"
         + $"- Review required: {(a.ReviewRequired ? "yes" : "no")}\n\n"
         + "This issue is closed by the pull request that adds the files.\n";

    public static string PullRequestBody(int issue, IReadOnlyList<string> written, IReadOnlyList<string> kept, IReadOnlyList<string>? removed = null)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("## Issue\n\nCloses #").Append(issue).Append("\n\n");
        sb.Append("## What and why\n\nAdds the convention v1 files, written by Repo Starter, so this repository works like every other one set up with it: ")
          .Append("the contributing guide and Git guide, the pull request and issue templates, CODEOWNERS, the CI, guard and board workflows, ")
          .Append("the Dependabot configuration, the local hooks and the manifest.\n\n");
        if (kept.Count > 0)
        {
            sb.Append("These files already existed and were left as they are:\n\n");
            foreach (var k in kept) sb.Append("- `").Append(k).Append("`\n");
            sb.Append('\n');
        }
        sb.Append("Files added:\n\n");
        foreach (var w in written) sb.Append("- `").Append(w).Append("`\n");
        if (removed is { Count: > 0 })
        {
            sb.Append("\nThese workflows also built every pull request, beside the convention's ci.yml, and are removed:\n\n");
            foreach (var r in removed) sb.Append("- `").Append(r).Append("`\n");
        }
        sb.Append("\n## How it was tested\n\nThe CI and Guard workflows run on this pull request for the first time; their results are the test.\n\n");
        sb.Append("## Checklist\n\n- [x] The pull request closes one issue, named above.\n- [x] No data files, keys, passwords or tokens are included.\n\n");
        sb.Append("## AI assistance\n\nNone. The files were generated by Repo Starter from its convention templates.\n");
        return sb.ToString();
    }

    // An update from the Check screen

    public static string UpdateIssueBody(IReadOnlyList<string> reasons)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("Repo Starter's Check found the repository had drifted from the convention. This issue is closed by the pull request that brings it back.\n\n");
        foreach (var r in reasons) sb.Append("- ").Append(r).Append('\n');
        return sb.ToString();
    }

    public static string UpdateCommitMessage(int issue, IReadOnlyList<string> written)
        => ConventionContent.UpdateIssueTitle + "\n\nWritten by Repo Starter's Check: "
         + (written.Count == 0 ? "the manifest." : $"{written.Count} convention file(s) and the manifest.")
         + (issue > 0 ? $"\n\nCloses #{issue}\n" : "\n");

    public static string UpdatePullRequestBody(int issue, IReadOnlyList<string> written, IReadOnlyList<string> reasons)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("## Issue\n\nCloses #").Append(issue).Append("\n\n");
        sb.Append("## What and why\n\nBrings the repository back to the convention. Repo Starter's Check found:\n\n");
        foreach (var r in reasons) sb.Append("- ").Append(r).Append('\n');
        sb.Append("\nFiles written:\n\n");
        foreach (var w in written) sb.Append("- `").Append(w).Append("`\n");
        sb.Append("\n## How it was tested\n\nThe CI and Guard workflows run on this pull request; their results are the test.\n\n");
        sb.Append("## Checklist\n\n- [x] The pull request closes one issue, named above.\n- [x] No data files, keys, passwords or tokens are included.\n\n");
        sb.Append("## AI assistance\n\nNone. The files were generated by Repo Starter from its convention templates.\n");
        return sb.ToString();
    }
}
