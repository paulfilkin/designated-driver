# Regenerates Resources\Strings.Designer.cs from Resources\Strings.resx.
# The dotnet CLI doesn't run Visual Studio's resx code generator, so run this after adding or renaming a string.
#   .\Tools\Update-Strings.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$resx = Join-Path $root 'Resources\Strings.resx'
$out = Join-Path $root 'Resources\Strings.Designer.cs'

[xml]$doc = Get-Content $resx -Encoding UTF8
$entries = @($doc.root.data | Where-Object { $_.name } | Sort-Object name)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//     Generated by Tools\Update-Strings.ps1 from Resources\Strings.resx. Do not edit by hand.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('using System.Globalization;')
[void]$sb.AppendLine('using System.Resources;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace DesignatedDriver.Resources;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// <summary>Every string the user sees, read from Strings.resx.</summary>')
[void]$sb.AppendLine('public static class Strings')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    private static readonly ResourceManager Manager = new("DesignatedDriver.Resources.Strings", typeof(Strings).Assembly);')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    public static CultureInfo? Culture { get; set; }')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    private static string Get(string name) => Manager.GetString(name, Culture) ?? name;')
foreach ($e in $entries) {
    $value = ($e.value -replace "`r?`n", ' ') -replace '\s+', ' '
    if ($value.Length -gt 90) { $value = $value.Substring(0, 87) + '...' }
    $comment = [System.Security.SecurityElement]::Escape($value)
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    /// <summary>$comment</summary>")
    [void]$sb.AppendLine("    public static string $($e.name) => Get(`"$($e.name)`");")
}
[void]$sb.AppendLine('}')

[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $($entries.Count) strings to $out"
